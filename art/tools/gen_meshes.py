#!/usr/bin/env python3
"""Generate src/shared/Data/Meshes.luau from art/fbx/manifest.json.

Run from anywhere:  python3 art/tools/gen_meshes.py

Rigged enemies (rigVersion 2 with a `rigAssetId`) get:
  assetId  = rigAssetId, parts = the rig parts (colour/material for the untextured ones), rig = { center, parts = [...] }
  legacy   = { assetId, parts } the old single-piece mesh, used by World/Assets when the rig asset fails to load
Everything else (env kit, enemies whose rig is not uploaded yet) keeps the plain `assetId` + `parts` (legacyParts when
the manifest entry is rig v2 but has no rigAssetId yet).
"""
import json
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
MANIFEST = os.path.join(ROOT, "art", "fbx", "manifest.json")
OUT = os.path.join(ROOT, "src", "shared", "Data", "Meshes.luau")
GUNMETAL_OLD = (74, 85, 104)
GUNMETAL_NEW = (96, 110, 132)
# Blender-made kits that are used in their own (Blender/Roblox Y-up -Z-forward) frame: set pieces, weapons, armour.
# They get `origin` (template-space position of the model origin) and `pivots` (manifest part pivots, model frame).
KIT_KINDS = ("setpiece", "weapon", "armor", "enemy_building")


def vec(v):
    return "Vector3.new(%s, %s, %s)" % tuple(repr(round(float(x), 4)) for x in v)


def part_line(p, indent="\t\t\t", tex=False):
    rgb = p.get("rgb")
    if rgb is None:
        r, g, b = 255, 255, 255  # textured rig-v2 parts carry no rgb (palette texture); white = no tint
    else:
        r, g, b = rgb
        if (r, g, b) == GUNMETAL_OLD:  # lighter gunmetal so robots read under dim/red light
            r, g, b = GUNMETAL_NEW
            p = dict(p, material="Metal")
    extra = ", textured = true" if (tex and p.get("textured")) else ""
    return '%s%s = { color = Color3.fromRGB(%d, %d, %d), material = Enum.Material.%s, role = "%s"%s },' % (
        indent, p["name"], r, g, b, p["material"], p["role"], extra)


def order_parents_first(parts):
    """Stable topological order: every part comes after its parent."""
    done, out, names = set(), [], {p["name"] for p in parts}
    pending = list(parts)
    while pending:
        progressed = False
        for p in list(pending):
            par = p.get("parent")
            if par is None or par not in names or par in done:
                out.append(p)
                done.add(p["name"])
                pending.remove(p)
                progressed = True
        if not progressed:
            raise SystemExit("rig parent cycle among: " + ", ".join(p["name"] for p in pending))
    return out


def main():
    with open(MANIFEST) as f:
        manifest = json.load(f)

    lines = [
        "-- GENERATED by art/tools/gen_meshes.py from art/fbx/manifest.json. Do not edit by hand.",
        "-- key -> { assetId, size (studs, Roblox XYZ), parts = { [MeshPart name] = { color, material, role } },",
        "--          rig? = { center, parts = { {name, role, parent?, pivot} } }, legacy? = { assetId, parts } }",
        "-- role: body | weak | trim | glow | armor | limb",
        "-- rig.center = bounding-box centre in the Blender/feet-origin frame; rig pivots are in that same frame (studs, Y up, -Z forward).",
        "-- World/Assets recentres templates on x/z, so template point = pivot - Vector3.new(center.X, 0, center.Z).",
        "-- Textured rig parts have a white colour (the palette atlas is in the mesh TextureID: do not tint).",
        "",
        "-- kit entries (set pieces, weapons, armour; manifest `kind`): origin = template-space position of the Blender model origin",
        "-- (Assets sets Model.WorldPivot to it, so PivotTo(cf) puts the origin at cf); pivots = manifest part pivots in that model frame;",
        "-- textured = the part carries a palette TextureID/SurfaceAppearance: never tint it.",
        "",
        "export type PartInfo = { color: Color3, material: Enum.Material, role: string, textured: boolean? }",
        "export type RigPart = { name: string, role: string, parent: string?, pivot: Vector3 }",
        "export type Rig = { center: Vector3, parts: { RigPart } }",
        "export type Legacy = { assetId: number, parts: { [string]: PartInfo } }",
        "export type MeshInfo = { assetId: number, size: Vector3, parts: { [string]: PartInfo }, rig: Rig?, legacy: Legacy?, kind: string?, origin: Vector3?, pivots: { [string]: Vector3 }? }",
        "",
        "local Meshes: { [string]: MeshInfo } = {",
    ]
    nrig = 0
    for key, v in manifest.items():
        sx, sy, sz = v["size_studs_roblox_xyz"]
        rig_id = v.get("rigAssetId")
        is_rig = v.get("rigVersion") == 2 and rig_id
        if v.get("rigVersion") == 2 and not rig_id:
            parts = v.get("legacyParts") or v["parts"]
        else:
            parts = v["parts"]
        lines.append("\t%s = {" % key)
        lines.append("\t\tassetId = %s," % (rig_id if is_rig else v["assetId"]))
        lines.append("\t\tsize = Vector3.new(%s, %s, %s)," % (sx, sy, sz))
        kit = v.get("kind") in KIT_KINDS and not is_rig
        if kit:
            lines.append('\t\tkind = "%s",' % v["kind"])
            cx, cy, cz = v["bbox_center_roblox"]
            lines.append("\t\torigin = %s," % vec((-cx, -(cy - sy / 2.0), -cz)))
        lines.append("\t\tparts = {")
        for p in (v["parts"] if is_rig else parts):
            lines.append(part_line(p, tex=kit))
        lines.append("\t\t},")
        if kit:
            lines.append("\t\tpivots = {")
            for p in v["parts"]:
                lines.append("\t\t\t%s = %s," % (p["name"], vec(p["pivot"])))
            lines.append("\t\t},")
        if is_rig:
            nrig += 1
            cx, cy, cz = v.get("bbox_center_roblox", (0, sy / 2.0, 0))
            lines.append("\t\trig = {")
            lines.append("\t\t\tcenter = %s," % vec((cx, cy, cz)))
            lines.append("\t\t\tparts = {")
            for p in order_parents_first(v["parts"]):
                par = p.get("parent")
                lines.append(
                    '\t\t\t\t{ name = "%s", role = "%s", %spivot = %s },'
                    % (p["name"], p["role"], ('parent = "%s", ' % par) if par else "", vec(p["pivot"]))
                )
            lines.append("\t\t\t},")
            lines.append("\t\t},")
            legacy = v.get("legacyParts")
            if legacy and v.get("assetId"):
                lines.append("\t\tlegacy = {")
                lines.append("\t\t\tassetId = %s," % v["assetId"])
                lines.append("\t\t\tparts = {")
                for p in legacy:
                    lines.append(part_line(p, "\t\t\t\t"))
                lines.append("\t\t\t},")
                lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    lines.append("")
    lines.append("return Meshes")
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", OUT, "(%d assets, %d rigged)" % (len(manifest), nrig))


if __name__ == "__main__":
    main()
